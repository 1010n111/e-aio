package com.eaio.common.util;

/**
 * 脱敏类型（展示层脱敏，存储仍是原文，符合 NFR-SEC-03）。
 *
 * <p>每种类型的掩码规则固定在此枚举，调用方只声明"这是手机号"，不自己拼掩码——
 * 规则一旦分散，就会出现同一种数据在不同接口呈现不同掩码。
 */
public enum SensitiveType {

    /** 手机号：保留前 3 后 4，如 {@code 138****5678}。 */
    MOBILE,

    /** 身份证：保留前 6 后 4，如 {@code 110101********1234}。 */
    ID_CARD,

    /** 银行卡：保留前 4 后 4。 */
    BANK_CARD,

    /** 邮箱：保留首字符与域名，如 {@code a****@example.com}。 */
    EMAIL,

    /** 姓名：保留姓氏，如 {@code 张**}/{@code 张*宁}。 */
    NAME,

    /** 地址：保留前 6 位。 */
    ADDRESS,

    /** 自定义：声明时必须同时给出保留位数，否则序列化直接报错（不静默输出原文）。 */
    CUSTOM
}
